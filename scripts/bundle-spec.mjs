// Embeds every file under spec/ into the engine, so the bundled CLI and MCP server are self-contained.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const specDir = path.join(root, 'spec');
const files = {};
const walk = (dir) => {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else files[path.relative(specDir, full).split(path.sep).join('/')] = fs.readFileSync(full, 'utf8');
  }
};
walk(specDir);
const out = path.join(root, 'packages/core/src/spec-files.generated.ts');
fs.writeFileSync(out, `// Generated by scripts/bundle-spec.mjs. Do not edit.\nexport const SPEC_FILES: Record<string, string> = ${JSON.stringify(files, null, 0)};\n`);
console.log(`spec bundled: ${Object.keys(files).length} files`);
